#!/usr/bin/env python3
"""
linkstream -- lazy incremental materialisation, as a monad.

The symbolic values of linkir (index polynomials, rank-1 factors)
never need to be expanded all at once. Materialising one is a
*stream*: elements are produced on demand, each from O(degree) state,
by the difference engine -- a polynomial's successive values are
generated by iterated cumulative sums (its forward differences), so
materialisation itself is literally a stack of cumsums.

A Gram inner product over two streams is an online fold: the state is
one running sum (and, in the rankop picture, running products of the
per-step factors), updated in O(1) per element pair, exact in
Fraction arithmetic, and equal to the Faulhaber closed form at the
end -- without ever holding the vectors.

Streams form a monad (pure / bind) with the usual combinators
(smap, scan = cumulative accumulation, zip_with); the laws are
checked in test_linkstream.py. Interactions between Links are again
Links at this level too: the Gram of two rank-1 symbolic matrices is
computed from their factors alone, as a scalar -- the operator-level
crosstalk inner product tr(A^T B) = ca*cb*(a_a.a_b)*(b_a.b_b).
"""
from fractions import Fraction
from math import comb

from linkir import _peval, _selem


class Stream:
    """A lazy producer. Wraps a zero-argument iterator factory so a
    stream can be traversed more than once when its source allows."""

    def __init__(self, make_iter):
        self._make = make_iter

    def __iter__(self):
        return self._make()

    # -- monad
    @staticmethod
    def pure(x):
        return Stream(lambda: iter([x]))

    @staticmethod
    def from_iterable(xs):
        return Stream(lambda: iter(xs))

    def bind(self, f):
        """f: value -> Stream. Concatenates the produced streams."""
        def gen():
            for x in self:
                yield from f(x)
        return Stream(gen)

    # -- combinators
    def smap(self, f):
        return Stream(lambda: (f(x) for x in self))

    def scan(self, f, init):
        """Cumulative accumulation: yields f(acc, x) after each x.
        cumsum is scan(+, 0); a cumulative product is scan(*, 1)."""
        def gen():
            acc = init
            for x in self:
                acc = f(acc, x)
                yield acc
        return Stream(gen)

    def zip_with(self, other, f):
        return Stream(lambda: (f(a, b) for a, b in zip(self, other)))

    def take(self, n):
        def gen():
            it = iter(self)
            for _ in range(n):
                try:
                    yield next(it)
                except StopIteration:
                    return
        return Stream(gen)

    def to_list(self, limit=None):
        if limit is None:
            return list(self)
        return list(self.take(limit))


def poly_stream(poly, ov=None, shift=Fraction(0), n=None):
    """Stream the values P(i) (i = 0, 1, 2, ...) of an index
    polynomial by the difference engine: the state is the vector of
    forward differences at the current index, advanced by iterated
    addition -- d cumulative sums deep, exact in Fractions.

    ov (head overrides) and shift follow linkir's symvec semantics:
    an override replaces the engine's value at its index, but the
    engine underneath keeps advancing on the polynomial itself.
    """
    ov = ov or {}
    d = len(poly) - 1
    while d > 0 and poly[d] == 0:
        d -= 1
    # D[k] = k-th forward difference of P at 0
    D = []
    for k in range(d + 1):
        s = Fraction(0)
        for j in range(k + 1):
            s += (-1) ** (k - j) * comb(k, j) * _peval(poly, Fraction(j))
        D.append(s)

    def gen():
        state = list(D)
        i = 0
        while n is None or i < n:
            val = state[0] + shift
            yield ov[i] if i in ov else val
            for k in range(d):
                state[k] += state[k + 1]
            i += 1
    return Stream(gen)


def symvec_stream(n, sv):
    poly, ov, shift = sv
    return poly_stream(poly, ov, shift, n=n)


def gram_online(a, b):
    """Stream the partial Gram sums of two streams: after each pair,
    the running total sum_i a_i*b_i. The fold state is a single
    accumulator -- the online form of the Gram inner product."""
    def gen():
        acc = Fraction(0)
        for x, y in zip(a, b):
            acc += x * y
            yield acc
    return Stream(gen)


def gram(a, b):
    """The full Gram inner product, folded online; exact."""
    acc = Fraction(0)
    for x, y in zip(a, b):
        acc += x * y
    return acc


def symmat_gram(m1, m2):
    """Crosstalk inner product of two rank-1 symbolic matrices
    (linkir symmat values): tr(A^T B) from the factors alone,
    = ca*cb * (a1.a2) * (b1.b2). An interaction of two Links,
    computed as a Link-level scalar; nothing is materialised."""
    from linkir import Builder
    b = Builder()
    fa = b._fdot(m1[1], m2[1])
    fb = b._fdot(m1[2], m2[2])
    return m1[3] * m2[3] * fa * fb
